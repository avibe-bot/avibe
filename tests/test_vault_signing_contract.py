def create_key(*, public_key=INTERNAL, protection="standard", scheme=KEYPATH, approval=False):
    with api._vault_engine().begin() as conn:
        vault_service.create_secret(
            conn, name="KEY", kind="keypair", protection=protection, signer_kind="local",
            sealed=Sealed(ciphertext="test-envelope", nonce="test-nonce", wrap_meta="test-meta"),
            public_meta={"signing_public_key": {"curve": "secp256k1", "public_key": public_key}} if public_key else {},
        )
        if approval:
            return vault_service.create_sign_request(conn, "KEY", digest=DIGEST, scheme=scheme)["id"]
    return None


@pytest.mark.parametrize("approval", [False, True], ids=["headless", "approval"])
@pytest.mark.parametrize("case", ["valid", "wrong-digest", "wrong-key", "raw-scheme", "tampered", "truncated"])
def test_standard_taproot_delivery_verifies_output_key_and_settles(monkeypatch, approval, case):
    """Returning raw-P/invalid signatures used to be reported as successful signing."""
    scheme = RAW if case == "raw-scheme" else KEYPATH
    request_id = create_key(public_key=G if case == "wrong-key" else INTERNAL, scheme=scheme, approval=approval)
    signature = dict(SIGNATURE)
    if case == "tampered":
        signature["signature"] = "00" + signature["signature"][2:]
    if case == "truncated":
        signature["signature"] = signature["signature"][:-2]
    sign = Mock(return_value=signature)
    monkeypatch.setattr(api, "avault_sign", sign)
    payload = {"name": "KEY", "scheme": scheme, "digest": DIGEST, "request_id": request_id}
    if case == "wrong-digest":
        # Keep the persisted request consistent: rejection must be cryptographic,
        # not merely a request identity mismatch before signing.
        payload["digest"] = "00" * 32
        if request_id:
            with api._vault_engine().begin() as conn:
                request_id = vault_service.create_sign_request(conn, "KEY", digest=payload["digest"], scheme=scheme)["id"]
            payload["request_id"] = request_id
    if case == "valid":
        result = api.vault_sign(payload)
        assert result["signature"] == SIGNATURE
        if request_id:
            assert result["request"]["status"] == "approved"
    else:
        with pytest.raises(api.VaultApiError, match="signature"):
            api.vault_sign(payload)
        if request_id:
            result = api.get_vault_request(request_id)
            assert result["request"]["status"] == "failed"
            assert not result.get("result")
        with api._vault_engine().connect() as conn:
            assert vault_service.get_secret_meta(conn, "KEY").get("last_used_at") is None
            events = conn.execute(select(vault_audit.c.event)).scalars().all()
            assert "signed" not in events
    sign.assert_called_once()


@pytest.mark.parametrize("valid", [False, True])
@pytest.mark.parametrize("approval", [False, True])
def test_standard_der_checks_the_pinned_key_before_delivery(monkeypatch, valid, approval):
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import ec

    request_id = create_key(public_key=G, scheme=DER, approval=approval)
    private = ec.derive_private_key(1 if valid else 6, ec.SECP256K1())
    r, s = utils.decode_dss_signature(private.sign(bytes.fromhex(DIGEST), ec.ECDSA(utils.Prehashed(hashes.SHA256()))))
    signature = {"signature": utils.encode_dss_signature(r, min(s, N - s)).hex()}
    monkeypatch.setattr(api, "avault_sign", Mock(return_value=signature))
    payload = {"name": "KEY", "digest": DIGEST, "scheme": DER, "request_id": request_id}
    if valid:
        assert api.vault_sign(payload)["signature"] == signature
    else:
        with pytest.raises(api.VaultApiError, match="does not verify"):
            api.vault_sign(payload)
        if request_id:
            assert api.get_vault_request(request_id)["request"]["status"] == "failed"



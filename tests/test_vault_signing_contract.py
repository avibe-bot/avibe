def test_real_sandbox_fixture_traverses_input_validator_persistence_and_signed_release(monkeypatch):
    """A helper-only fixture previously hid a literal-backslash-n input validator bug."""
    release = SANDBOX["signedContext"]["release"]
    create_key(protection="protected", public_key=release["publicKey"])
    monkeypatch.setattr(api, "_notify_vault_request_created", Mock())
    context = copy.deepcopy(release["signingContext"])
    result = api.request_vault_sign({
        "name": "KEY", "digest": release["digest"], "scheme": release["scheme"],
        "signing_context": context, "delivery": {"publicKey": G, "name": "untrusted"},
    })
    signed = result["request"]["delivery"]["operation_context"]
    assert signed["release"] == {**release, "name": "KEY"}
    assert hashlib.sha256(context["canonicalPreimage"].encode()).hexdigest() == release["digest"]
    # Verify an actual daemon signature, and that editing any bound operation byte
    # invalidates it; client-supplied display/delivery cannot replace the release.
    unsigned = dict(signed)
    signature = unsigned.pop("signature")
    with api._vault_engine().begin() as conn:
        key = api._load_or_create_vault_daemon_binding_key(conn)
    public = ed25519.Ed25519PublicKey.from_public_bytes(base64.b64decode(key["publicKey"]))
    public.verify(base64.b64decode(signature["value"]), api._vault_sandbox_canonical_json(unsigned).encode())
    from cryptography.exceptions import InvalidSignature

    for field, value in (("name", "OTHER"), ("scheme", DER), ("digest", "00" * 32), ("publicKey", INTERNAL), ("signingContext", {})):
        changed = copy.deepcopy(unsigned)
        changed["release"][field] = value
        with pytest.raises(InvalidSignature):
            public.verify(base64.b64decode(signature["value"]), api._vault_sandbox_canonical_json(changed).encode())
    canonical_fixture = copy.deepcopy(SANDBOX["signedContext"])
    canonical_fixture.pop("signature")
    assert api._vault_sandbox_canonical_json(canonical_fixture) == SANDBOX["canonicalUnsignedContext"]



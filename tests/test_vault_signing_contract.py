N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
BIP341 = json.loads((FIXTURES / "bip341-wallet.json").read_text())["keyPathSpending"][0]["inputSpending"][0]
DIGEST = BIP341["intermediary"]["sigHash"]
INTERNAL = "02" + BIP341["intermediary"]["internalPubkey"]
SIGNATURE = {"signature": BIP341["expected"]["witness"][0][:-2]}

def _bip340_vectors():
    with (FIXTURES / "bip340.csv").open() as stream:
        # The public API signs only 32-byte digests, not arbitrary-length messages.
        return [row for row in csv.DictReader(stream) if len(row["message"]) == 64]


@pytest.mark.parametrize("vector", _bip340_vectors(), ids=lambda row: "bip340-" + row["index"])
def test_raw_bip340_official_positive_and_negative_vectors(vector):
    kwargs = dict(
        signing_public_key={"curve": "secp256k1", "public_key": vector["public key"]},
        digest=vector["message"], scheme=RAW, signature={"signature": vector["signature"]},
    )
    if vector["verification result"] == "TRUE":
        api._verify_standard_signature(**kwargs)
    else:
        with pytest.raises(api.VaultApiError):
            api._verify_standard_signature(**kwargs)


